// Builds supabase/imports/nith-import.sql from the checked-in import pack and decisions.
//
//   node scripts/build-nith-import.mjs
//
// The SQL only inserts or updates rows with the pack's own record ids, so running it again
// changes nothing and no other row is touched. It needs the 20261010180000 migration.
// It holds no credentials: apply it with `supabase db query --linked -f <file>` or paste it
// into the Supabase SQL editor.

import fs from "node:fs"

const pack = JSON.parse(fs.readFileSync("data/nith-import-pack.json", "utf8"))
const decisions = JSON.parse(fs.readFileSync("data/nith-import-decisions.json", "utf8"))

const q = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`)
const text = (value) => q(value ?? "")
const isDate = (value) => typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value)
const date = (value) => {
  if (value === null || value === undefined) return "null"
  if (!isDate(value)) throw new Error(`Not a date-only value: ${value}`)
  return `date ${q(value)}`
}
const url = (value) => {
  if (!value) return "''"
  if (!/^https?:\/\/\S+$/.test(value)) throw new Error(`Not a web address: ${value}`)
  return q(value)
}

const lines = [
  "-- Generated by scripts/build-nith-import.mjs from data/nith-import-pack.json and",
  "-- data/nith-import-decisions.json. Do not edit by hand; change the data and rebuild.",
  "--",
  "-- Imports public NIT Hamirpur records into UniFlow. Safe to run more than once: every",
  "-- statement is keyed on the record id, and no other row is read or changed. It creates no",
  "-- club memberships and no accounts.",
  "",
  "begin;",
  "",
]

// ---- clubs
const clubs = pack.clubs.map((club) => {
  const decision = decisions.clubs[club.record_id]
  if (!decision) throw new Error(`No decision for ${club.record_id}`)
  return { id: club.record_id, name: club.name, description: decision.description, category: club.category, website: club.official_webpage, sourceUrl: club.evidence_url, checkedOn: club.verification_date }
})
lines.push("insert into public.clubs (id, name, description, category, website, source_url, source_checked_on) values")
lines.push(clubs.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${text(c.description)}, ${text(c.category)}, ${url(c.website)}, ${url(c.sourceUrl)}, ${date(c.checkedOn)})`).join(",\n"))
lines.push("on conflict (id) do update set")
lines.push("  name = excluded.name, description = excluded.description, category = excluded.category,")
lines.push("  website = excluded.website, source_url = excluded.source_url, source_checked_on = excluded.source_checked_on;")
lines.push("")

// ---- updates
const audience = (value) => (Array.isArray(value) ? value.join("; ") : value ?? "")
const updates = []
const skipped = []
for (const record of [...pack.events, ...pack.notices]) {
  const decision = decisions.updates[record.record_id]
  if (!decision) throw new Error(`No decision for ${record.record_id}`)
  if (!decision.publish) { skipped.push(`${record.record_id}: ${decision.reason}`); continue }
  if (record.start_time || record.end_time) throw new Error(`${record.record_id} has a time; map it explicitly`)
  updates.push({
    id: record.record_id,
    clubId: record.related_club_record_id,
    title: record.title,
    description: decision.description,
    category: record.type,
    startDate: record.start_date,
    endDate: record.end_date,
    timezone: record.timezone,
    venue: decision.venue ?? record.venue,
    eligibility: decision.eligibility ?? (record.eligibility || audience(record.audience)),
    registrationUrl: record.registration_url,
    department: record.department,
    publisher: decision.publisher,
    sourceUrl: record.original_source_url,
    deadlineDate: decision.deadline_date,
    sourcePublishedOn: decision.source_published_on,
  })
}

lines.push("-- reviewed_at records when the sources were checked and the record admitted; it is kept")
lines.push("-- on later runs. No start time, end time, or deadline time is set: the sources give none.")
lines.push("insert into public.events (")
lines.push("  id, club_id, status, title, description, category, start_date, end_date, timezone, venue, eligibility,")
lines.push("  registration_url, source, source_name, department, review_confirmed, reviewed_at,")
lines.push("  publisher_name, source_url, deadline_date, source_published_on")
lines.push(") values")
lines.push(
  updates
    .map((u) =>
      `  (${q(u.id)}, ${q(u.clubId)}, 'published', ${q(u.title)}, ${text(u.description)}, ${q(u.category)}, ${date(u.startDate)}, ${date(u.endDate)}, ${q(u.timezone)}, ${text(u.venue)}, ${text(u.eligibility)},\n` +
      `   ${url(u.registrationUrl)}, 'Imported source', ${q(`Imported from ${u.publisher}`)}, ${text(u.department)}, true, now(),\n` +
      `   ${q(u.publisher)}, ${url(u.sourceUrl)}, ${date(u.deadlineDate)}, ${date(u.sourcePublishedOn)})`,
    )
    .join(",\n"),
)
lines.push("on conflict (id) do update set")
lines.push("  title = excluded.title, description = excluded.description, category = excluded.category,")
lines.push("  start_date = excluded.start_date, end_date = excluded.end_date, timezone = excluded.timezone,")
lines.push("  venue = excluded.venue, eligibility = excluded.eligibility, registration_url = excluded.registration_url,")
lines.push("  source = excluded.source, source_name = excluded.source_name, department = excluded.department,")
lines.push("  status = excluded.status, review_confirmed = excluded.review_confirmed,")
lines.push("  reviewed_at = coalesce(public.events.reviewed_at, excluded.reviewed_at),")
lines.push("  publisher_name = excluded.publisher_name, source_url = excluded.source_url,")
lines.push("  deadline_date = excluded.deadline_date, source_published_on = excluded.source_published_on;")
lines.push("")
lines.push("commit;")
lines.push("")

fs.mkdirSync("supabase/imports", { recursive: true })
fs.writeFileSync("supabase/imports/nith-import.sql", lines.join("\n"))
console.log(`clubs: ${clubs.length}`)
console.log(`updates published: ${updates.length} (${updates.map((u) => u.id).join(", ")})`)
console.log(`updates not published: ${skipped.length}`)
skipped.forEach((entry) => console.log(`  ${entry}`))
console.log(`unresolved, not imported: ${pack.unresolved.length}`)
